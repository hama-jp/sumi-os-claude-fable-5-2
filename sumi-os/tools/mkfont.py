#!/usr/bin/env python3
"""Convert PSF1/PSF2 console fonts (gzip) into C glyph tables for Sumi OS.
usage: mkfont.py out.c name=file.psf.gz ...
Emits glyphs for code points 0..255 (Latin-1), resolved through the PSF unicode table."""
import gzip, struct, sys

def load(path):
    d = gzip.open(path, 'rb').read()
    if d[:2] == b'\x36\x04':
        mode, h = d[2], d[3]
        n = 512 if mode & 1 else 256
        w = 8; bpg = h; off = 4; has_uni = bool(mode & 6)
        glyphs = [d[off + i*bpg: off + (i+1)*bpg] for i in range(n)]
        umap = {}
        if has_uni:
            p = off + n*bpg; g = 0
            while p + 1 < len(d) and g < n:
                v = struct.unpack_from('<H', d, p)[0]; p += 2
                if v == 0xFFFF: g += 1; continue
                if v == 0xFFFE:  # sequence start: skip to terminator
                    while struct.unpack_from('<H', d, p)[0] != 0xFFFF: p += 2
                    continue
                umap.setdefault(v, g)
    elif d[:4] == b'\x72\xb5\x4a\x86':
        ver, hs, flags, n, bpg, h, w = struct.unpack_from('<7I', d, 4)
        glyphs = [d[hs + i*bpg: hs + (i+1)*bpg] for i in range(n)]
        umap = {}
        if flags & 1:
            tbl = d[hs + n*bpg:]; g = 0
            for entry in tbl.split(b'\xff')[:n]:
                seq = entry.split(b'\xfe')[0]
                try:
                    for ch in seq.decode('utf-8'): umap.setdefault(ord(ch), g)
                except UnicodeDecodeError: pass
                g += 1
    else:
        raise SystemExit("not a PSF font: " + path)
    return w, h, glyphs, umap

out = open(sys.argv[1], 'w')
out.write('/* Generated by tools/mkfont.py from Terminus Font (SIL OFL 1.1). Do not edit. */\n#include "gfx.h"\n')
for spec in sys.argv[2:]:
    name, path = spec.split('=')
    w, h, glyphs, umap = load(path)
    bpr = (w + 7) // 8
    out.write('static const unsigned char %s_data[256*%d] = {\n' % (name, bpr*h))
    for cp in range(256):
        g = umap.get(cp, cp if (not umap and cp < len(glyphs)) else umap.get(0xFFFD, umap.get(ord('?'), 0)))
        if cp < 32 or 127 <= cp < 160: g = umap.get(32, 32)
        out.write(''.join('0x%02x,' % b for b in glyphs[g][:bpr*h]) + '\n')
    out.write('};\nconst Font %s = { %d, %d, %d, %s_data };\n' % (name, w, h, bpr, name))
out.close()
