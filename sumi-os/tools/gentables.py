#!/usr/bin/env python3
"""Generate the fixed-point sine table used by the kernel (no floating point at run time)."""
import math, sys
out = open(sys.argv[1], 'w')
out.write('/* Generated by tools/gentables.py. sin(0..90 degrees in 0.1 degree steps) * 4096 */\n')
out.write('const short sin_table[901] = {\n')
for i in range(901):
    out.write('%d,' % round(math.sin(math.radians(i / 10)) * 4096))
    if i % 16 == 15: out.write('\n')
out.write('};\n')
