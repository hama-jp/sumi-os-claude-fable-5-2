#!/usr/bin/env python3
"""Turn `nm -n kernel.elf` output into a C symbol table so the panic screen can name functions."""
import sys
syms = []
for line in open(sys.argv[1]):
    parts = line.split()
    if len(parts) == 3 and parts[1] in 'tT':
        syms.append((int(parts[0], 16), parts[2]))
syms.sort()
out = open(sys.argv[2], 'w')
out.write('/* Generated by tools/mksyms.py. */\ntypedef struct KSym { unsigned addr; const char *name; } KSym;\n')
out.write('const KSym ksyms[] = {\n')
for a, n in syms: out.write('  { 0x%08x, "%s" },\n' % (a, n))
out.write('};\nconst int ksym_count = %d;\n' % len(syms))
